#!/bin/sh
# Fetches the compressed Parakeet Ultra speech model (ADR 0025, ADR 0014) into the app's gitignored
# Resources/Models/ParakeetUltra/ so it ships inside the app and captions need no network.
#
# Every file is checked against the size and sha256 in scripts/models/$VARIANT.sha256, whatever the host serves.
# Idempotent: a folder that already matches the manifest is left alone.
#
#   scripts/fetch-asr-models.sh                       # from the GitHub Release asset
#   SEAL_MODEL_SOURCE=mini scripts/fetch-asr-models.sh # from the Mac mini's copy (rsync --checksum)
#   scripts/fetch-asr-models.sh --write-manifest DIR  # maintainers: write the manifest from a reviewed folder
#
# Switching to the 4-bit fallback build is this one line (plus its manifest and asset).
set -eu
VARIANT="ultra-pal6"
NAME="ParakeetUltra"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MANIFEST="$ROOT/scripts/models/$VARIANT.sha256"
DEST="${SEAL_MODEL_DEST:-$ROOT/Apps/Spike/Resources/Models/$NAME}"
RELEASE_URL="https://github.com/G-Eskayo/clarity-captions/releases/download/models-$VARIANT/$NAME-$VARIANT.zip"
MINI_HOST="gils-mac-mini"
MINI_PATH="edacc-eval/models/release/$VARIANT/$NAME"

# check DIR: exit 0 if DIR holds exactly the manifest's files with the right sizes and hashes.
check() {
    python3 -I - "$MANIFEST" "$1" <<'PY'
import hashlib, os, sys
manifest, folder = sys.argv[1:3]
want = {}
for line in open(manifest):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    digest, size, rel = line.split(None, 2)
    want[rel] = (digest, int(size))
if not want:
    sys.exit("manifest is empty: " + manifest)
have = set()
for base, dirs, files in os.walk(folder):
    for f in files:
        if f == ".DS_Store":
            continue
        have.add(os.path.relpath(os.path.join(base, f), folder))
problems = ["missing " + r for r in sorted(set(want) - have)] + ["unexpected " + r for r in sorted(have - set(want))]
for rel in sorted(set(want) & have):
    path = os.path.join(folder, rel)
    digest, size = want[rel]
    if os.path.getsize(path) != size:
        problems.append("size mismatch " + rel)
        continue
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    if h.hexdigest() != digest:
        problems.append("checksum mismatch " + rel)
if problems:
    print("\n".join(problems[:20]), file=sys.stderr)
    sys.exit(1)
print("OK: %d files verified in %s" % (len(want), folder))
PY
}

if [ "${1:-}" = "--write-manifest" ]; then
    SRC="${2:?usage: --write-manifest DIR}"
    python3 -I - "$SRC" "$VARIANT" > "$MANIFEST" <<'PY'
import hashlib, os, sys
folder, variant = sys.argv[1:3]
print("# %s: sha256  size  path, relative to Resources/Models/ParakeetUltra/. Generated by fetch-asr-models.sh." % variant)
rows = []
for base, dirs, files in os.walk(folder):
    for f in files:
        if f == ".DS_Store":
            continue
        path = os.path.join(base, f)
        h = hashlib.sha256()
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        rows.append((os.path.relpath(path, folder), h.hexdigest(), os.path.getsize(path)))
for rel, digest, size in sorted(rows):
    print("%s  %d  %s" % (digest, size, rel))
PY
    echo "wrote $MANIFEST"
    exit 0
fi

if [ -d "$DEST" ] && check "$DEST" 2>/dev/null; then
    exit 0
fi

STAGING="$(mktemp -d "${TMPDIR:-/tmp}/seal-asr.XXXXXX")"
trap 'rm -rf "$STAGING"' EXIT
case "${SEAL_MODEL_SOURCE:-github}" in
    github)
        echo "downloading $RELEASE_URL"
        curl -fL --retry 3 -o "$STAGING/model.zip" "$RELEASE_URL"
        unzip -q "$STAGING/model.zip" -d "$STAGING/unzipped"
        FETCHED="$STAGING/unzipped/$NAME"
        ;;
    mini)
        if [ -d "$HOME/$MINI_PATH" ]; then SRC="$HOME/$MINI_PATH/"; else SRC="$MINI_HOST:$MINI_PATH/"; fi
        echo "copying from $SRC"
        mkdir -p "$STAGING/$NAME"
        rsync -a --checksum --exclude .DS_Store "$SRC" "$STAGING/$NAME/"
        FETCHED="$STAGING/$NAME"
        ;;
    *)
        echo "SEAL_MODEL_SOURCE must be github or mini" >&2
        exit 2
        ;;
esac

# Verify before anything touches the app folder: a bad download never replaces a good copy.
check "$FETCHED"
mkdir -p "$(dirname "$DEST")"
rm -rf "$DEST.old"
[ -d "$DEST" ] && mv "$DEST" "$DEST.old"
mv "$FETCHED" "$DEST"
rm -rf "$DEST.old"
check "$DEST"
