#!/bin/sh
# "Sound like the speaker" (#247, PR #254): turns the table `ear-spike calibrate` measured into the Swift file the app
# ships, so the phone never measures a voice. Renders only: nothing plays.
#   swift build -c release --package-path Packages/EarSpike
#   Packages/EarSpike/.build/release/ear-spike calibrate --out /tmp/cal
#   scripts/ship-voice-calibrations.sh /tmp/cal/voice-calibrations.json
set -eu
json="${1:?usage: ship-voice-calibrations.sh voice-calibrations.json}"
out="$(dirname "$0")/../Packages/CaptionCore/Sources/CaptionCore/VoiceCalibrationData.swift"
/usr/bin/plutil -lint -s "$json" >/dev/null 2>&1 || python3 -c 'import json,sys; json.load(open(sys.argv[1]))' "$json"
{
  printf '// Generated by scripts/ship-voice-calibrations.sh from `ear-spike calibrate` (PR #254). Do not edit by hand.\n'
  printf '// Each installed voice'"'"'s own pitch and pace and how pitchMultiplier and rate move it, measured once on a Mac.\n\n'
  printf 'let shippedVoiceCalibrationsJSON = #"""\n'
  cat "$json"
  printf '\n"""#\n'
} > "$out"
echo "wrote $out"
