"""The #220 report: every Core ML build of the zipformer next to #217's sherpa-onnx int8 build and Apple, with sizes,
latency and the recommended build.

    python -m zipformer_coreml.report --shards <dir> --results <dir> --builds <dir> --latency <dir> --out <md>
        [--json-out <json>]

Scoring is #217's (`score_hebrew`: the #202 normaliser, strict CER and WER, 95% bootstrap over recordings). The rule
the owner set (2026-10-30): recommend the smallest build whose CER interval still overlaps the int8 build's, and still
beats Apple by a wide margin. Here that is, on both eval-d1 and eval-whatsapp: the CER intervals overlap int8's, the
build's upper CER bound is below Apple's lower bound, and its CER is at most half of Apple's.
"""
from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from pathlib import Path

from edacc_eval.report_hebrew import SET_NAMES, HebrewCell, _ci, _pct, score_hebrew
from edacc_eval.results import load_results

from .run import model_name

SHERPA_INT8 = "zipformer2-66m-streaming-he-int8"
APPLE = "DictationTranscriber he-IL"
SETS = ("eval-d1", "eval-whatsapp")
ORDER = ("fp32", "fp16", "int8", "pal6", "pal4", "pal3", "pal2")
LABELS = {"fp32": "Core ML fp32 (conversion check)", "fp16": "Core ML fp16", "int8": "Core ML int8 (linear)",
          "pal6": "Core ML 6-bit palettized", "pal4": "Core ML 4-bit palettized", "pal3": "Core ML 3-bit palettized",
          "pal2": "Core ML 2-bit palettized"}


def _overlaps(a, b) -> bool:
    return a.cer.low <= b.cer.high and b.cer.low <= a.cer.high


def qualifies(cell: HebrewCell, int8: HebrewCell, apple: HebrewCell) -> bool:
    return _overlaps(cell, int8) and cell.cer.high < apple.cer.low and cell.cer.value <= apple.cer.value / 2


def choose(scores: dict, sizes: dict[str, int]) -> str | None:
    """The smallest variant (by bytes on disk) that qualifies on every set in SETS; None if none does or a reference
    row is missing. scores: set → {label: HebrewCell}."""
    for v in sorted(sizes, key=lambda k: (sizes[k], ORDER.index(k) if k in ORDER else 99)):
        ok = True
        for s in SETS:
            cells = scores.get(s, {})
            c, i8, ap = cells.get(model_name(v)), cells.get(SHERPA_INT8), cells.get(APPLE)
            if c is None or i8 is None or ap is None or not qualifies(c, i8, ap):
                ok = False
                break
        if ok:
            return v
    return None


def read_sizes(builds: Path) -> dict[str, int]:
    out = {}
    for p in sorted(Path(builds).glob("*/sizes.json")):
        out[p.parent.name] = sum(json.loads(p.read_text()).values())
    return out


def _mb(n: int) -> str:
    return f"{n / 1e6:.1f} MB"


def build_report(scores: dict, sizes: dict, parts: dict, latency: dict, pick: str | None) -> str:
    L = ["# Hebrew zipformer on Core ML: compressed builds (#220)", "",
         "Generated by `python -m zipformer_coreml.report`. Method: `docs/perf/hebrew-coreml-design.md`.", ""]
    head = "| Build | Size on disk | " + " | ".join(f"{SET_NAMES.get(s, s)} CER | WER" for s in SETS) + " |"
    L += [head, "|" + "---|" * (2 + 2 * len(SETS))]
    rows = [(LABELS.get(v, v), model_name(v), _mb(sizes[v])) for v in ORDER if v in sizes]
    rows += [("sherpa-onnx int8 (#217, what the owner compared)", SHERPA_INT8, "70.6 MB"),
             ("Apple DictationTranscriber he-IL (#217)", APPLE, "0 MB to Seal")]
    for name, label, size in rows:
        cells = []
        for s in SETS:
            c = scores.get(s, {}).get(label)
            cells += [f"{_pct(c.cer.value)} ({_ci(c.cer)})", f"{_pct(c.wer.value)} ({_ci(c.wer)})"] if c else ["–", "–"]
        bold = "**" if label == model_name(pick or "") else ""
        L.append(f"| {bold}{name}{bold} | {size} | " + " | ".join(cells) + " |")
    L += ["", "Sizes are the three `.mlpackage` folders (encoder, decoder, joiner). Parts per build:", ""]
    L += [f"- {LABELS.get(v, v)}: " + ", ".join(f"{k} {_mb(n)}" for k, n in parts[v].items()) for v in ORDER
          if v in parts]
    if latency:
        L += ["", "## Latency and memory on the Mac (one build per process)", "",
              "| Build | Load | First word (median) | Steady (median, p95) | Compute per 1.28 s chunk (median, p95) "
              "| Faster than real time | Peak memory |", "|---|---|---|---|---|---|---|"]
        for v in ORDER:
            r = latency.get(v)
            if not r:
                continue
            L.append(f"| {LABELS.get(v, v)} | {r['load_seconds']:.2f} s | {r['first_word_seconds_median']:.2f} s | "
                     f"{r['steady_seconds_median']:.2f} s, {r['steady_seconds_p95']:.2f} s | "
                     f"{r['chunk_compute_ms_median']:.0f} ms, {r['chunk_compute_ms_p95']:.0f} ms | "
                     f"{r['x_realtime']:.0f}× | {r['peak_rss_mb']:.0f} MB |")
    L += ["", "## Recommendation", ""]
    if pick:
        L.append(f"**{LABELS.get(pick, pick)}, {_mb(sizes[pick])}**: the smallest build whose CER interval overlaps "
                 "the int8 build's on both sets and whose CER stays under half of Apple's, with the intervals apart.")
    else:
        L.append("No build met the rule; see the table.")
    return "\n".join(L) + "\n"


def write(shards: Path, results: Path, builds: Path, latency_dir: Path | None, out: Path,
          json_out: Path | None = None) -> str | None:
    from edacc_eval.shards import read_manifest
    manifest = []
    for s in SETS:
        index = json.loads((Path(shards) / s / "index.json").read_text())
        manifest += [m for name in index["shards"] for m in read_manifest(Path(shards) / s / name)]
    rows, _ = load_results(sorted(Path(results).glob("*.jsonl")))
    scores = {k: v.cells for k, v in score_hebrew(manifest, rows).items()}
    sizes = read_sizes(builds)
    parts = {p.parent.name: json.loads(p.read_text()) for p in Path(builds).glob("*/sizes.json")}
    latency = {}
    if latency_dir and Path(latency_dir).is_dir():
        for p in Path(latency_dir).glob("*.json"):
            r = json.loads(p.read_text())
            latency[r["variant"]] = r
    pick = choose(scores, {k: v for k, v in sizes.items() if k != "fp32"})
    Path(out).write_text(build_report(scores, sizes, parts, latency, pick), encoding="utf-8")
    if json_out:
        Path(json_out).write_text(json.dumps({
            "recommended": pick, "sizes": sizes, "parts": parts, "latency": latency,
            "scores": {s: {lab: asdict(c) for lab, c in cells.items()} for s, cells in scores.items()}},
            indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return pick


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--shards", type=Path, required=True)
    ap.add_argument("--results", type=Path, required=True)
    ap.add_argument("--builds", type=Path, required=True)
    ap.add_argument("--latency", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--json-out", type=Path)
    a = ap.parse_args(argv)
    print("recommended:", write(a.shards, a.results, a.builds, a.latency, a.out, a.json_out))


if __name__ == "__main__":
    main()
