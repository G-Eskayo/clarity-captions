"""Render scoreboard to markdown and JSON."""
from __future__ import annotations

import json
from pathlib import Path
from scoreboard_eval.row import ScoreboardRow
from scoreboard_eval.build import build_scoreboard


def format_metric(value: float | None, metric_name: str) -> str:
    """Format value based on metric type."""
    if value is None:
        return "–"
    if metric_name in ("lag_ms", "lag"):
        return f"{value:.0f} ms"
    if metric_name in ("speed_x_realtime", "speed"):
        return f"{value:.1f}x"
    return f"{value * 100:.1f}%"


def format_percentage(value: float | None) -> str:
    """Format as percentage with 1 decimal place."""
    if value is None:
        return "–"
    return f"{value * 100:.1f}%"


def format_ci(lo: float | None, hi: float | None) -> str:
    """Format confidence interval."""
    if lo is None or hi is None:
        return "–"
    return f"{lo * 100:.1f}% – {hi * 100:.1f}%"


def format_number(value: float | None, decimals: int = 1) -> str:
    """Format as number."""
    if value is None:
        return "–"
    if decimals == 0:
        return f"{int(value)}"
    return f"{value:.{decimals}f}"


def write_scoreboard(perf_dir: Path, md_out: Path, json_out: Path | None = None) -> None:
    """Generate engine-scoreboard.md and optional JSON."""
    perf_dir = Path(perf_dir)
    result = build_scoreboard(perf_dir)
    rows = result.rows

    md_lines = [
        "# Engine Scoreboard",
        "",
        "Generated by `scripts/engine-eval/scoreboard_eval`. Do not edit by hand.",
        "",
    ]

    tasks = {}
    for row in rows:
        if row.task not in tasks:
            tasks[row.task] = []
        tasks[row.task].append(row)

    for task_name in sorted(tasks.keys()):
        md_lines.append(f"## {task_name}")
        md_lines.append("")

        task_rows = tasks[task_name]

        if not task_rows:
            md_lines.append("No data.")
            md_lines.append("")
            continue

        headers = ["Engine", "Language", "Test Set", "Metric", "Value", "95% CI", "Lag (ms)", "Size", "Speed"]
        md_lines.append("| " + " | ".join(headers) + " |")
        md_lines.append("| " + " | ".join(["---"] * len(headers)) + " |")

        for row in sorted(task_rows, key=lambda r: (r.engine, r.language)):
            cells = [
                row.engine,
                row.language,
                row.test_set,
                row.metric_name,
                format_metric(row.metric_value, row.metric_name),
                format_ci(row.ci_low, row.ci_high),
                format_number(row.lag_ms, 0),
                f"{row.size_bytes // 1000000:.0f} MB" if row.size_bytes else "–",
                format_number(row.speed_x_realtime, 1) + "x" if row.speed_x_realtime else "–",
            ]
            md_lines.append("| " + " | ".join(cells) + " |")

        md_lines.append("")

    if result.gaps:
        md_lines.append("## Gaps")
        md_lines.append("")
        for task, reason in sorted(result.gaps.items()):
            md_lines.append(f"- **{task}**: {reason}")
        md_lines.append("")

    md_out.parent.mkdir(parents=True, exist_ok=True)
    md_out.write_text("\n".join(md_lines))

    if json_out:
        json_data = {
            "rows": [
                {
                    "task": r.task,
                    "language": r.language,
                    "language_code": r.language_code,
                    "engine": r.engine,
                    "platform": r.platform,
                    "test_set": r.test_set,
                    "metric_name": r.metric_name,
                    "metric_value": r.metric_value,
                    "ci_low": r.ci_low,
                    "ci_high": r.ci_high,
                    "lag_ms": r.lag_ms,
                    "size_bytes": r.size_bytes,
                    "zipped_bytes": r.zipped_bytes,
                    "memory_bytes": r.memory_bytes,
                    "heat": r.heat,
                    "speed_x_realtime": r.speed_x_realtime,
                    "source_ticket": r.source_ticket,
                    "source_file": r.source_file,
                    "note": r.note,
                }
                for r in rows
            ],
            "gaps": result.gaps,
        }
        json_out.parent.mkdir(parents=True, exist_ok=True)
        json_out.write_text(json.dumps(json_data, indent=2))
